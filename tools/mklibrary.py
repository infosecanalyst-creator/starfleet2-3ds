"""Build sf2ui/library_data.h from assets/library-port.txt (the port's own Library cards).

Card format: "# Title", "@shelf START|BRIDGE|PROCEDURES|PROBLEMS|REFERENCE", optional "@see <manual
section title>" lines, then paragraphs (one per line) and, for checklists,
"STEP <button or -> | <what to do> | <text the game shows when done, or ->".
The header is checked in, so a build without python still works."""
import os, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
src = os.path.join(root, 'assets', 'library-port.txt')
out = os.path.join(root, 'sf2ui', 'library_data.h')
SHELVES = ['START', 'BRIDGE', 'PROCEDURES', 'PROBLEMS', 'REFERENCE']
def esc(s):
    s = s.encode('ascii', 'replace').decode()
    return s.replace('\\', '\\\\').replace('"', '\\"')
cards = []
if os.path.exists(src):
    cur = None
    for line in open(src, encoding='utf-8', errors='replace'):
        line = line.rstrip('\n').rstrip('\r')
        if line.startswith('# '):
            cur = {'title': line[2:].strip(), 'shelf': 0, 'see': [], 'lines': []}; cards.append(cur)
        elif cur is None: continue
        elif line.startswith('@shelf '):
            w = line[7:].strip().upper()
            if w not in SHELVES: sys.exit('unknown shelf %r in card %r' % (w, cur['title']))
            cur['shelf'] = SHELVES.index(w)
        elif line.startswith('@see '): cur['see'].append(line[5:].strip())
        else: cur['lines'].append(line)
    for c in cards:
        while c['lines'] and not c['lines'][-1].strip(): c['lines'].pop()
        while c['lines'] and not c['lines'][0].strip(): c['lines'].pop(0)
with open(out, 'w', newline='\n') as f:
    f.write('// Generated by tools/mklibrary.py from assets/library-port.txt. Do not edit.\n')
    f.write('struct LibCard { const char* title; int shelf; const char* see; const char* text; };\n')
    f.write('static const LibCard LIBCARDS[] = {\n')
    for c in cards:
        f.write('  {"%s", %d, "%s",\n   "%s"},\n' % (esc(c['title']), c['shelf'], esc('|'.join(c['see'])), esc('\n'.join(c['lines'])).replace('\n', '\\n')))
    f.write('  {0, 0, 0, 0}\n};\n')
print('library_data.h: %d cards' % len(cards))
