#!/usr/bin/env python3
"""Generate sf2ui/fonts.h from Terminus BDF files.

Each font becomes a 256-glyph table in CP437 order (the DOS character set the
game uses). A glyph is <height> rows; each row is one byte, bit 7 = leftmost
pixel. Box-drawing and block characters are also drawn procedurally at run time
(so borders join at any cell size); the glyphs here are the fallback.

Terminus Font: SIL Open Font License 1.1 (see assets/OFL.txt). Tamzen: see assets/Tamzen-LICENSE.
"""
import sys

LOWCHARS = {0x01: 0x263A, 0x02: 0x263B, 0x03: 0x2665, 0x04: 0x2666, 0x05: 0x2663, 0x06: 0x2660,
            0x07: 0x2022, 0x08: 0x25D8, 0x09: 0x25CB, 0x0A: 0x25D9, 0x0B: 0x2642, 0x0C: 0x2640,
            0x0D: 0x266A, 0x0E: 0x266B, 0x0F: 0x263C, 0x10: 0x25BA, 0x11: 0x25C4, 0x12: 0x2195,
            0x13: 0x203C, 0x14: 0x00B6, 0x15: 0x00A7, 0x16: 0x25AC, 0x17: 0x21A8, 0x18: 0x2191,
            0x19: 0x2193, 0x1A: 0x2192, 0x1B: 0x2190, 0x1C: 0x221F, 0x1D: 0x2194, 0x1E: 0x25B2,
            0x1F: 0x25BC, 0x7F: 0x2302}


def load_bdf(path):
    glyphs, props = {}, {}
    lines = open(path, encoding='latin-1').read().split('\n')
    i = 0
    while i < len(lines):
        L = lines[i]
        if L.startswith('FONTBOUNDINGBOX'):
            props['fbb'] = list(map(int, L.split()[1:]))
        elif L.startswith('FONT_ASCENT'):
            props['ascent'] = int(L.split()[1])
        elif L.startswith('FONT_DESCENT'):
            props['descent'] = int(L.split()[1])
        elif L.startswith('STARTCHAR'):
            enc = bbx = None; bits = []
            while not lines[i].startswith('ENDCHAR'):
                t = lines[i]
                if t.startswith('ENCODING'): enc = int(t.split()[1])
                elif t.startswith('BBX'): bbx = list(map(int, t.split()[1:]))
                elif t == 'BITMAP':
                    i += 1
                    while not lines[i].startswith('ENDCHAR'):
                        bits.append(int(lines[i], 16) if lines[i].strip() else 0); i += 1
                    break
                i += 1
            glyphs[enc] = (bbx, bits)
        i += 1
    return glyphs, props


def unicode_for(code):
    if code == 0:
        return 0x20
    if code < 0x20 or code == 0x7F:
        return LOWCHARS.get(code, 0x20)
    return ord(bytes([code]).decode('cp437'))


def build(path, w, h, fallback=None):
    glyphs, props = load_bdf(path)
    fb = load_bdf(fallback)[0] if fallback else {}
    ascent = props.get('ascent', props['fbb'][1] + props['fbb'][3])
    out, missing = [], []
    for code in range(256):
        u = unicode_for(code)
        g = glyphs.get(u) or fb.get(u)
        if g is None:
            missing.append(code); g = glyphs.get(ord('?'))
        (bw, bh, bx, by), bits = g
        nbytes = (bw + 7) // 8
        rows = [0] * h
        top = ascent - (bh + by)
        for r, row in enumerate(bits):
            y = top + r
            if not (0 <= y < h):
                continue
            for c in range(bw):
                if row & (1 << (nbytes * 8 - 1 - c)):
                    x = bx + c
                    if 0 <= x < w:
                        rows[y] |= 0x80 >> x
        out.append(rows)
    return out, missing


def main():
    fonts = [('ter_6x12', 'assets/ter-u12n.bdf', 6, 12),
             ('ter_8x14', 'assets/ter-u14n.bdf', 8, 14),
             ('ter_8x16', 'assets/ter-u16n.bdf', 8, 16),
             ('tam_5x9', 'assets/Tamzen5x9r.bdf', 5, 9, 'assets/misc-fixed-5x8.bdf')]
    o = ['// Generated by tools/mkfont.py from Terminus Font (SIL OFL 1.1). Do not edit.',
         '#pragma once', '#include <stdint.h>', '']
    for name, path, w, h, *fb in fonts:
        glyphs, missing = build(path, w, h, fb[0] if fb else None)
        if missing:
            print(f'{name}: {len(missing)} CP437 codes fall back to "?": {missing}', file=sys.stderr)
        o.append(f'static const uint8_t {name}[256][{h}] = {{')
        for code, rows in enumerate(glyphs):
            o.append('  {' + ','.join(f'0x{r:02x}' for r in rows) + f'}}, // {code:#04x}')
        o.append('};')
        o.append('')
    open('sf2ui/fonts.h', 'w').write('\n'.join(o) + '\n')
    print('wrote sf2ui/fonts.h')


if __name__ == '__main__':
    main()
